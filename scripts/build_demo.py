def build():
    result = []
    for ident, kind, title, topic, level, stages, industries, description in ROWS:
        paid = kind == "course" and ident not in {"startup-course", "marketing-course"}
        content = (
            None
            if paid
            else (
                "Это авторский демонстрационный материал, а не публикация Альфа-Курса.\n\n"
                + description
                + "\n\n1. Опишите текущую ситуацию и один ожидаемый результат.\n"
                "2. Запишите исходные данные и предположения, которые нужно проверить.\n"
                "3. Выберите небольшое действие и заранее определите, по чему оцените результат.\n"
                "4. После проверки зафиксируйте наблюдение и следующий вопрос.\n\n"
                "Этот учебный пример показывает работу маршрута и не заменяет профильную консультацию."
            )
        )
        result.append(
            dict(
                id="demo-" + ident,
                source_type=kind,
                title=title,
                description=description,
                topics=[topic],
                industries=industries.split(",") if industries else [],
                tags=[],
                stage=stages.split(","),
                difficulty=level,
                access="paid" if paid else "free",
                price=None,
                duration=None,
                url=None,
                published=True,
                provenance="synthetic",
                demo_content=content,
                related_ids=[],
            )
        )
    target = ROOT / "backend/data/demo.json"
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(json.dumps(result, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(f"Created {len(result)} explicitly synthetic materials")


if __name__ == "__main__":
    build()
