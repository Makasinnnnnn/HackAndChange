import {chromium} from 'playwright';
import fs from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const directory=fileURLToPath(new URL('../../docs/screenshots',import.meta.url));
const base=process.env.E2E_BASE_URL||'http://127.0.0.1:3080';
await fs.mkdir(directory,{recursive:true});
const browser=await chromium.launch({channel:'chrome',headless:true});
const page=await browser.newPage({baseURL:base,viewport:{width:1440,height:820}});
await page.goto(base);
await page.getByRole('button',{name:'Построить маршрут',exact:true}).waitFor();
await page.waitForFunction(()=>!document.querySelector('button.primary')?.disabled);
const info=await page.request.get(base+'/api/ready');
if((await info.json()).catalog_mode!=='demo')throw Error('Never publish organizer catalog screenshots');
await page.screenshot({path:path.join(directory,'desktop-demo.png')});
await page.getByRole('button',{name:/Привлечь клиентов/}).click();
await page.locator('.route-card').first().waitFor();
await page.locator('.route-results').scrollIntoViewIfNeeded();
await page.screenshot({path:path.join(directory,'route-demo.png')});
await page.getByRole('button',{name:'Для жюри',exact:true}).click();
const personas=await (await page.request.get('/api/demo/profiles')).json();
await page.getByRole('combobox',{name:'Демонстрационный предприниматель'}).click();
await page.getByRole('option',{name:personas.find(persona=>persona.id==='cafe').name,exact:true}).click();
await page.getByRole('button',{name:'Сравнить алгоритмы',exact:true}).click();
await page.locator('.comparison-column .route-card').first().waitFor();
await page.evaluate(()=>{const e=document.querySelector('.comparison-grid');scrollTo(0,e.getBoundingClientRect().top+scrollY-20);});
await page.screenshot({path:path.join(directory,'comparison-demo.png')});
await page.setViewportSize({width:390,height:844});
await page.goto(base);
await page.waitForFunction(()=>!document.querySelector('button.primary')?.disabled);
await page.screenshot({path:path.join(directory,'mobile-demo.png'),fullPage:true});
await browser.close();
console.log('Captured four screenshots of the synthetic demo');
